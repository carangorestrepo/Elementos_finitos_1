clear
clc
format long g

syms C1 C2 C3 C4 C5 C6 ...
     alfa beta k Ac ...
     qy1 qy2 qx1 qx2 ...
     x L EI EA real
%% ========================================================================
% PROPIEDADES
% ========================================================================
E  = 24870062.3;
G  = 0.4*E;
L  = 4;
Ae = 0.4^2;
I  = 0.4^4/12;
Ac = Ae*G*5/6;
k  = 500;
EI = E*I;
EA = E*Ae;
%% ========================================================================
% CARGAS
% ========================================================================
qx1 = 20;
qx2 = 25;
qy1 = 25;
qy2 = 30;
qx = qx1 + (qx2-qx1)*x/L;
qy = qy1 + (qy2-qy1)*x/L;
%% ========================================================================
% PARAMETROS DE LA SOLUCION
% ========================================================================
a = k/Ac;
b = k/EI;
alfa = 0.5*sqrt(a + 2*sqrt(b));
beta = 0.5*sqrt(2*sqrt(b) - a);
%% ========================================================================
% FUNCIONES HOMOGENEAS TRANSVERSALES
% ========================================================================
f1 = cosh(alfa*x)*cos(beta*x);
f2 = cosh(alfa*x)*sin(beta*x);
f3 = sinh(alfa*x)*cos(beta*x);
f4 = sinh(alfa*x)*sin(beta*x);
F = [f1 f2 f3 f4];
F1 = diff(F,x);
F2 = diff(F,x,2);
F3 = diff(F,x,3);
%% ========================================================================
% COEFICIENTES DE v, M, V, t
% ========================================================================
Av = F;
AM = EI*(F2 - k/Ac*F);
AV = EI*(F3 - k/Ac*F1);
At = F1 + AV/Ac;
%% ========================================================================
% PARTE AXIAL HOMOGENEA
% ========================================================================
% u_h = C6 + C5*x/EA
%
% N_h = C5
%% ========================================================================
% MATRIZ FUNDAMENTAL COMPLETA
%
% Y = [u;v;t;N;V;M]
% ========================================================================
Z = sym(zeros(1,4));
Afun = [ ...
    Z,  x/EA, 1;
    Av, 0,    0;
    At, 0,    0;
    Z,  1,    0;
    AV, 0,    0;
    AM, 0,    0];
%% ========================================================================
% SOLUCION PARTICULAR AXIAL
%
% Equilibrio:
%
% N' = -qx
% ========================================================================
Np = -qx1*x ...
     -(qx2-qx1)*x^2/(2*L);
up = -qx1*x^2/(2*EA) ...
     -(qx2-qx1)*x^3/(6*EA*L);
%% ========================================================================
% SOLUCION PARTICULAR TRANSVERSAL
% ========================================================================
vp = qy/k;
tp = (qy2-qy1)/(k*L);
Vp = sym(0);
Mp = sym(0);
%% ========================================================================
% VECTOR PARTICULAR COMPLETO
% ========================================================================
P = [ ...
    up;
    vp;
    tp;
    Np;
    Vp;
    Mp];
%% ========================================================================
% MATRIZ DE DESPLAZAMIENTOS
% ========================================================================
Ad = Afun(1:3,:);
B0 = double(subs(Ad,x,0));
BL = double(subs(Ad,x,L));
B = [B0;
     BL];
%% ========================================================================
% DESPLAZAMIENTOS PARTICULARES EN LOS NODOS
% ========================================================================
Pd = P(1:3);
dp = [ ...
    double(subs(Pd,x,0));
    double(subs(Pd,x,L))];
%% ========================================================================
% MATRIZ DE FUERZAS DE EXTREMO
%
% f = [-N1;
%       V1;
%      -M1;
%       N2;
%      -V2;
%       M2]
% ========================================================================
Af = [ ...
    -Afun(4,:);
     Afun(5,:);
    -Afun(6,:)];
Sf0 = double(subs(Af,x,0));
AfL = [ ...
     Afun(4,:);
    -Afun(5,:);
     Afun(6,:)];
SfL = double(subs(AfL,x,L));
S = [Sf0;
     SfL];
%% ========================================================================
% FUERZAS PARTICULARES DE EXTREMO
% ========================================================================

fp0 = [ ...
    -double(subs(Np,x,0));
     double(subs(Vp,x,0));
    -double(subs(Mp,x,0))];

fpL = [ ...
     double(subs(Np,x,L));
    -double(subs(Vp,x,L));
     double(subs(Mp,x,L))];

fp = [fp0;
      fpL];


%% ========================================================================
% MATRIZ DE RIGIDEZ
% ========================================================================

K = S/B;

K = 0.5*(K + K.');


%% ========================================================================
% FUERZAS NODALES EQUIVALENTES
%
% fint = K*d - feq
% ========================================================================

feq = K*dp - fp;


%% ========================================================================
% RESULTADOS
% ========================================================================

disp('Matriz de rigidez K =')
disp(K)

disp('Vector de fuerzas nodales equivalentes =')
disp(feq)
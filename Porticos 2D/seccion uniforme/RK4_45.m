%% ========================================================================
% RESPUESTA DINAMICA DE UN SISTEMA SDOF SOMETIDO A UN ACELEROGRAMA
%
% Metodo de integracion:
% Runge-Kutta-Fehlberg RKF45 de paso constante
%
% Ecuacion de movimiento:
%
%       m*u'' + c*u' + k*u = -m*ag(t)
%
% Dividiendo entre m:
%
%       u'' + 2*xi*w*u' + w^2*u = -ag(t)
%
% Estado:
%
%       y(1) = u       desplazamiento relativo
%       y(2) = u'      velocidad relativa
%
% -------------------------------------------------------------------------
% Basado en la formulacion RKF45
% ========================================================================
%clear
%clc
%close all
function u=RK4_45(xi,T,ag)
%% ========================================================================
% 1. ACELEROGRAMA
% ========================================================================
%ag = load('ELCENTRO.TXT');
ag = ag(:);          % asegurar vector columna
dt = 0.02;           % [s] intervalo del acelerograma
nDatos = length(ag);
% Numero de intervalos de integracion
N = nDatos - 1;
% Vector de tiempo correspondiente al acelerograma
t = (0:N)*dt;
%{
fprintf('Numero de datos       = %d\n',nDatos);
fprintf('Numero de intervalos  = %d\n',N);
fprintf('Paso temporal         = %.5f s\n',dt);
fprintf('Duracion registro     = %.5f s\n',t(end));
fprintf('Aceleracion maxima    = %.8f\n',max(ag));
fprintf('Aceleracion minima    = %.8f\n',min(ag));
%}
%% ========================================================================
% 2. PROPIEDADES DEL SISTEMA
% ========================================================================
m = 1;                 % masa
%xi = 0.05;             % relacion de amortiguamiento
%T = 0.126;             % [s] periodo natural
w = 2*pi/T;            % [rad/s] frecuencia circular
k = m*w^2;             % rigidez
c = 2*m*w*xi;          % amortiguamiento viscoso
%fprintf('\n');
%fprintf('Periodo T              = %.6f s\n',T);
%fprintf('Frecuencia w            = %.6f rad/s\n',w);
%fprintf('Masa                    = %.6f\n',m);
%fprintf('Rigidez                 = %.6f\n',k);
%fprintf('Amortiguamiento         = %.6f\n',c);
%% ========================================================================
% 3. CONDICIONES INICIALES
% ========================================================================
% Estado:
%
% y(1) = desplazamiento relativo
% y(2) = velocidad relativa
y = [0;
     0];

h = dt;
%% ========================================================================
% 4. PREALOCACION
% ========================================================================
ys = zeros(2,nDatos);
ys(:,1) = y;
% Error estimado RKF45
error_RKF = zeros(2,N);
%% ========================================================================
% 5. COEFICIENTES RUNGE-KUTTA-FEHLBERG
% ========================================================================
a2 = 1/4;
a3 = 3/8;
a4 = 12/13;
a5 = 1;
a6 = 1/2;
% -------------------------------------------------------------------------
% Coeficientes b
% -------------------------------------------------------------------------
b21 = 1/4;
b31 = 3/32;
b32 = 9/32;
b41 = 1932/2197;
b42 = -7200/2197;
b43 = 7296/2197;
b51 = 439/216;
b52 = -8;
b53 = 3680/513;
b54 = -845/4104;
b61 = -8/27;
b62 = 2;
b63 = -3544/2565;
b64 = 1859/4104;
b65 = -11/40;
% -------------------------------------------------------------------------
% Aproximacion de orden 4
% -------------------------------------------------------------------------
c1 = 25/216;
c3 = 1408/2565;
c4 = 2197/4104;
c5 = -1/5;
% -------------------------------------------------------------------------
% Diferencia entre orden 5 y orden 4
% utilizada para estimar el error
% -------------------------------------------------------------------------
d1 = 1/360;
d3 = -128/4275;
d4 = -2197/75240;
d5 = 1/50;
d6 = 2/55;
%% ========================================================================
% 6. INTEGRACION EN EL TIEMPO
% ========================================================================
for i = 1:N
    % ---------------------------------------------------------------------
    % Aceleraciones conocidas en los extremos del intervalo
    %
    % t_i ------------------- t_i+1
    % ag_i                    ag_i+1
    %
    % Se supone interpolacion lineal dentro del intervalo.
    % ---------------------------------------------------------------------
    ag_i = ag(i);
    ag_f = ag(i+1);
    % ---------------------------------------------------------------------
    % Aceleraciones en los puntos internos de RKF45
    % ---------------------------------------------------------------------
    ag1 = ag_i;
    ag2 = ag_i + a2*(ag_f-ag_i);
    ag3 = ag_i + a3*(ag_f-ag_i);
    ag4 = ag_i + a4*(ag_f-ag_i);
    ag5 = ag_f;
    ag6 = ag_i + a6*(ag_f-ag_i);
    % ---------------------------------------------------------------------
    % k1
    % ---------------------------------------------------------------------
    k1 = F(y,ag1,m,c,k);
    % ---------------------------------------------------------------------
    % k2
    % ---------------------------------------------------------------------
    y2 = y ...
       + h*b21*k1;
    k2 = F(y2,ag2,m,c,k);
    % ---------------------------------------------------------------------
    % k3
    % ---------------------------------------------------------------------
    y3 = y ...
       + h*( ...
             b31*k1 ...
           + b32*k2 );

    k3 = F(y3,ag3,m,c,k);
    % ---------------------------------------------------------------------
    % k4
    % ---------------------------------------------------------------------
    y4 = y ...
       + h*( ...
             b41*k1 ...
           + b42*k2 ...
           + b43*k3 );
    k4 = F(y4,ag4,m,c,k);
    % ---------------------------------------------------------------------
    % k5
    % ---------------------------------------------------------------------
    y5 = y ...
       + h*( ...
             b51*k1 ...
           + b52*k2 ...
           + b53*k3 ...
           + b54*k4 );
    k5 = F(y5,ag5,m,c,k);
    % ---------------------------------------------------------------------
    % k6
    % ---------------------------------------------------------------------
    y6 = y ...
       + h*( ...
             b61*k1 ...
           + b62*k2 ...
           + b63*k3 ...
           + b64*k4 ...
           + b65*k5 );
    k6 = F(y6,ag6,m,c,k);
    %% --------------------------------------------------------------------
    % SOLUCION RKF ORDEN 4
    % ---------------------------------------------------------------------
    y_nueva = y ...
            + h*( ...
                  c1*k1 ...
                + c3*k3 ...
                + c4*k4 ...
                + c5*k5 );
    %% --------------------------------------------------------------------
    % ESTIMACION DEL ERROR
    %
    % y(5) - y(4)
    % ---------------------------------------------------------------------
    error_RKF(:,i) = h*( ...
                          d1*k1 ...
                        + d3*k3 ...
                        + d4*k4 ...
                        + d5*k5 ...
                        + d6*k6 );
    %% --------------------------------------------------------------------
    % ACTUALIZAR ESTADO
    % ---------------------------------------------------------------------
    y = y_nueva;
    ys(:,i+1) = y;
end
%% ========================================================================
% 7. RESPUESTA RELATIVA
% ========================================================================
u = ys(1,:);
v = ys(2,:);
%% ========================================================================
% 8. ACELERACION RELATIVA
%
%   udd = -ag - c/m*v - k/m*u
%
% ========================================================================
udd = zeros(1,nDatos);
for i = 1:nDatos
    udd(i) = -ag(i) ...
             - (c/m)*v(i) ...
             - (k/m)*u(i);
end
%{
%% ========================================================================
% 9. ACELERACION ABSOLUTA
%
%   u_abs'' = u'' + ag
%
% De la ecuacion:
%
%   u_abs'' = -(c/m)*u' - (k/m)*u
%
% ========================================================================
udd_abs = udd + ag.';
%% ========================================================================
% 10. VALORES MAXIMOS
% ========================================================================
[umax,iu] = max(abs(u));
[vmax,iv] = max(abs(v));
[amax,ia] = max(abs(udd_abs));
fprintf('\nRESULTADOS\n');
fprintf('-----------------------------------------------\n');
fprintf('Desplazamiento relativo max = %.10e\n',umax);
fprintf('Tiempo                     = %.5f s\n',t(iu));
fprintf('\n');
fprintf('Velocidad relativa max     = %.10e\n',vmax);
fprintf('Tiempo                     = %.5f s\n',t(iv));
fprintf('\n');
fprintf('Aceleracion absoluta max   = %.10e\n',amax);
fprintf('Tiempo                     = %.5f s\n',t(ia));
%% ========================================================================
% 11. GRAFICAS
% ========================================================================
figure
subplot(4,1,1)
plot(t,ag,'k')
grid on
xlabel('Tiempo [s]')
ylabel('a_g')
title('Acelerograma')
subplot(4,1,2)
plot(t,u,'k')
grid on
xlabel('Tiempo [s]')
ylabel('u')
title('Desplazamiento relativo')
subplot(4,1,3)
plot(t,v,'k')
grid on
xlabel('Tiempo [s]')
ylabel('du/dt')
title('Velocidad relativa')
subplot(4,1,4)
plot(t,udd_abs,'k')
grid on
xlabel('Tiempo [s]')
ylabel('a_{abs}')
title('Aceleracion absoluta')
%% ========================================================================
% 12. ERROR ESTIMADO RKF45
% ========================================================================
figure
plot(t(2:end),abs(error_RKF(1,:)),'k')
grid on
xlabel('Tiempo [s]')
ylabel('|Error estimado|')
title('Error estimado RKF45 - desplazamiento')
%}
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% FUNCION DEL SISTEMA DINAMICO
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    function res = F(y,ag,m,c,k)
        % ---------------------------------------------------------------------
        % Variables de estado
        % ---------------------------------------------------------------------
        u = y(1);          % desplazamiento relativo
        v = y(2);          % velocidad relativa
        % ---------------------------------------------------------------------
        % Ecuacion de movimiento
        %
        % m*u'' + c*u' + k*u = -m*ag
        %
        % u'' = -ag - c/m*u' - k/m*u
        % ---------------------------------------------------------------------
        a = -ag ...
            - (c/m)*v ...
            - (k/m)*u;
        % ---------------------------------------------------------------------
        % Sistema de primer orden
        % ---------------------------------------------------------------------
        res = [v;
               a];
    end
end